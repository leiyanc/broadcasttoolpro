from io import BytesIO
from html import escape
from pathlib import Path

from reportlab.lib import colors
from reportlab.lib.pagesizes import letter
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import inch
from reportlab.platypus import Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle


BRAND_LOGO = Path(__file__).resolve().parents[2] / "assets" / "broadcast-tool-pro-logo.png"


def generate_public_xmltv_report(payload: dict, language: str = "en") -> bytes:
    spanish = language == "es"
    copy = {
        "title": "Reporte básico de validación XMLTV" if spanish else "Basic XMLTV Validation Report",
        "format": "FORMATO XMLTV" if spanish else "XMLTV FORMAT",
        "operations": "PREPARACIÓN OPERATIVA" if spanish else "OPERATIONAL READINESS",
        "profile": "PERFIL DE ENTREGA BTP" if spanish else "BTP DELIVERY PROFILE",
        "passed": "Aprobado" if spanish else "Passed",
        "attention": "Requiere atención" if spanish else "Needs attention",
        "ready": "Listo" if spanish else "Ready",
        "review": "Revisión recomendada" if spanish else "Review recommended",
        "channels": "Canales" if spanish else "Channels",
        "programmes": "Programas" if spanish else "Programmes",
        "findings": "Hallazgos" if spanish else "Findings",
        "layer": "Capa" if spanish else "Layer",
        "severity": "Severidad" if spanish else "Severity",
        "rule": "Regla" if spanish else "Rule",
        "line": "Línea" if spanish else "Line",
        "message": "Mensaje" if spanish else "Message",
        "format_short": "Formato" if spanish else "Format",
        "operations_short": "Oper." if spanish else "Ops",
        "profile_short": "BTP",
        "none": "No se encontraron hallazgos." if spanish else "No findings were identified.",
        "footer": "Generado por Broadcast Tool Pro · Validador XMLTV gratuito" if spanish else "Generated by Broadcast Tool Pro · Free XMLTV Validator",
    }
    xmltv = payload.get("xmltv") or {}
    operations = payload.get("operational") or {}
    profile = payload.get("btp_profile") or {}
    output = BytesIO()
    document = SimpleDocTemplate(
        output,
        pagesize=letter,
        leftMargin=0.5 * inch,
        rightMargin=0.5 * inch,
        topMargin=0.45 * inch,
        bottomMargin=0.62 * inch,
        title=copy["title"],
        author="Broadcast Tool Pro",
        pageCompression=0,
    )
    styles = getSampleStyleSheet()
    title_style = ParagraphStyle("BTPTitle", parent=styles["Title"], fontName="Helvetica-Bold", fontSize=19, leading=23, textColor=colors.HexColor("#102A43"))
    body = ParagraphStyle("BTPBody", parent=styles["BodyText"], fontName="Helvetica", fontSize=7.5, leading=10, textColor=colors.HexColor("#243B53"))
    cell = ParagraphStyle("BTPCell", parent=body, fontSize=6.6, leading=8.2)
    cell_center = ParagraphStyle("BTPCellCenter", parent=cell, alignment=1)
    summary_header = ParagraphStyle(
        "BTPSummaryHeader",
        parent=cell_center,
        textColor=colors.white,
        fontName="Helvetica-Bold",
    )
    severity_short = {
        "critical": "Crít." if spanish else "Crit.",
        "error": "Error",
        "warning": "Aviso" if spanish else "Warn.",
        "recommendation": "Rec.",
    }
    summary = [
        [Paragraph(copy["format"], summary_header), Paragraph(copy["operations"], summary_header), Paragraph(copy["profile"], summary_header)],
        [Paragraph(copy["passed"] if payload.get("valid") else copy["attention"], cell_center), Paragraph(copy["ready"] if payload.get("operational_ready") else copy["review"], cell_center), Paragraph(f'{profile.get("score", 0)}/100', cell_center)],
        [Paragraph(f'{xmltv.get("critical", 0)} critical · {xmltv.get("errors", 0)} errors', cell_center), Paragraph(f'{operations.get("errors", 0)} errors · {operations.get("warnings", 0)} warnings', cell_center), Paragraph(f'{profile.get("recommendations", 0)} recommendations', cell_center)],
    ]
    summary_table = Table(summary, colWidths=[2.33 * inch] * 3)
    summary_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#102A43")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("BACKGROUND", (0, 1), (-1, -1), colors.HexColor("#EAF2FF")),
        ("TEXTCOLOR", (0, 1), (-1, -1), colors.HexColor("#102A43")),
        ("FONTNAME", (0, 0), (-1, 1), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 7.5),
        ("ALIGN", (0, 0), (-1, -1), "CENTER"),
        ("GRID", (0, 0), (-1, -1), 0.4, colors.HexColor("#D7E1EC")),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    rows = [[copy["layer"], copy["severity"], copy["rule"], copy["line"], copy["message"]]]
    for label, section in ((copy["format_short"], xmltv), (copy["operations_short"], operations), (copy["profile_short"], profile)):
        for issue in section.get("issues") or []:
            severity = str(issue.get("severity") or "")
            rows.append([
                Paragraph(label, cell),
                Paragraph(severity_short.get(severity, severity), cell),
                Paragraph(str(issue.get("rule_id") or ""), cell),
                Paragraph(str(issue.get("row") or "—"), cell_center),
                Paragraph(escape(str(issue.get("message") or "")), cell),
            ])
    if len(rows) == 1:
        rows.append(["—", "—", "—", "—", copy["none"]])
    issues_table = Table(rows, colWidths=[0.64 * inch, 0.55 * inch, 0.68 * inch, 0.38 * inch, 5.23 * inch], repeatRows=1)
    issues_table.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#102A43")),
        ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"),
        ("FONTSIZE", (0, 0), (-1, -1), 6.6),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("GRID", (0, 0), (-1, -1), 0.3, colors.HexColor("#D7E1EC")),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, colors.HexColor("#F7FAFC")]),
        ("TOPPADDING", (0, 0), (-1, -1), 4),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
    ]))
    story = [
        Paragraph(copy["title"], title_style),
        Paragraph(f'{escape(str(payload.get("filename") or "XMLTV file"))} · {copy["channels"]}: {payload.get("channels", 0)} · {copy["programmes"]}: {payload.get("programmes", 0)}', body),
        Spacer(1, 12), summary_table, Spacer(1, 14),
        Paragraph(copy["findings"], ParagraphStyle("Section", parent=title_style, fontSize=12, leading=15)),
        Spacer(1, 6), issues_table,
    ]

    def footer(canvas, _doc):
        canvas.saveState()
        canvas.setStrokeColor(colors.HexColor("#D7E1EC"))
        canvas.line(0.5 * inch, 0.42 * inch, 8.0 * inch, 0.42 * inch)
        canvas.setFillColor(colors.HexColor("#627D98"))
        canvas.setFont("Helvetica", 7)
        canvas.drawString(0.5 * inch, 0.25 * inch, copy["footer"])
        canvas.drawCentredString(letter[0] / 2, 0.25 * inch, str(canvas.getPageNumber()))
        canvas.drawImage(
            str(BRAND_LOGO),
            letter[0] - document.rightMargin - 86,
            7,
            width=86,
            height=19,
            preserveAspectRatio=True,
            mask="auto",
        )
        canvas.restoreState()

    document.build(story, onFirstPage=footer, onLaterPages=footer)
    return output.getvalue()
